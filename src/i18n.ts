export type MessageKey = keyof typeof messages.en;

export function resolveLocale(settings: CalendarOfNotesSettings): SupportedLocale {
  if (settings.language !== "auto") return settings.language;
  return moment.locale().toLowerCase().startsWith("ko") ? "ko" : "en";
}

export function t(settings: CalendarOfNotesSettings, key: MessageKey): string {
  return messages[resolveLocale(settings)][key];
}

export function intlLocale(settings: CalendarOfNotesSettings): string {
  return resolveLocale(settings) === "ko" ? "ko-KR" : "en-US";
}
